"""Output writer (Architecture §11.7): App folders for the UNO Q, sketch folders for the classic Uno.

Writes into a temporary sibling directory and replaces the target only if it is empty or was
written by iotc (marker file .iotc-build); anything else is refused (exit 2), so a typo in -o can
never wipe a user folder.
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path

from .. import __version__
from ..ir import IRProgram
from ..source import write_bytes, write_text
from . import linux_py, mcu_cpp, webpage

MARKER = ".iotc-build"
TEMPLATES = Path(__file__).parent / "templates" / "blink-with-ui"
RESERVED = {"con", "prn", "aux", "nul", *(f"com{i}" for i in range(1, 10)), *(f"lpt{i}" for i in range(1, 10))}


class OutputError(Exception):
    """The output directory cannot be used (exit code 2)."""


def slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9_]", "_", name.lower()).strip("_") or "app"
    if s[0].isdigit() or s in RESERVED:
        s = "app_" + s
    return s


def _check_target(out: Path) -> None:
    if out.exists():
        if not out.is_dir():
            raise OutputError(f"{out} exists and is not a directory")
        if any(out.iterdir()) and not (out / MARKER).exists():
            raise OutputError(f"refusing to overwrite {out}: it is not empty and was not written by iotc")


def _commit(tmp: Path, out: Path) -> None:
    if out.exists():
        shutil.rmtree(out)
    tmp.rename(out)


def _app_yaml(name: str, description: str, web: bool) -> str:
    bricks = "bricks:\n  - arduino:web_ui\n" if web else "bricks: []\n"
    return f"name: {name}\nicon: \U0001F331\ndescription: {description}\n{bricks}"


IDLE_MAIN = '''"""GENERATED by iotc - the mcu-only target runs everything on the microcontroller."""
import time

from arduino.app_utils import App


def loop() -> None:
    time.sleep(1.0)


print("iotc mcu-only App: all rules run on the MCU; watch the LEDs and the LED matrix", flush=True)
App.run(user_loop=loop)
'''


def write(ir: IRProgram, out: str | Path, input_mode: str = "pins",
          scenario: list[list[int]] | None = None, report=None, demo_controls: bool = False) -> list[str]:
    """Write the build output; return the written relative paths (sorted)."""
    out = Path(out)
    _check_target(out)
    tmp = out.with_name(out.name + ".iotc-tmp")
    if tmp.exists():
        shutil.rmtree(tmp)
    tmp.mkdir(parents=True)
    files = mcu_cpp.emit(ir, input_mode, scenario)
    stem = Path(ir.name).stem
    written: list[str] = []
    try:
        if ir.board == "uno":
            # classic Uno: a plain sketch folder (arduino-cli needs <dir>/<dir>.ino)
            ino = f"{out.name}.ino"
            write_text(tmp / ino, files["sketch.ino"])
            write_text(tmp / "iotc_gen.h", files["iotc_gen.h"])
            written += [ino, "iotc_gen.h"]
        else:
            unoq = ir.target == "unoq"
            desc = f"Generated by iotc {__version__} from {stem} ({ir.target}, input {input_mode})"
            write_text(tmp / "app.yaml", _app_yaml(f"{stem} (iotc)", desc, web=unoq))
            write_text(tmp / "sketch" / "sketch.ino", files["sketch.ino"])
            write_text(tmp / "sketch" / "iotc_gen.h", files["iotc_gen.h"])
            write_bytes(tmp / "sketch" / "sketch.yaml", (TEMPLATES / "sketch" / "sketch.yaml").read_bytes())
            written += ["app.yaml", "sketch/sketch.ino", "sketch/iotc_gen.h", "sketch/sketch.yaml", "python/main.py"]
            if unoq:
                write_text(tmp / "python" / "main.py", linux_py.emit_main(ir, input_mode, scenario, demo_controls))
                extra = {**linux_py.runtime_files(), **webpage.assets(ir, report, input_mode, scenario, demo_controls)}
                for rel, data in sorted(extra.items()):
                    write_bytes(tmp / rel, data)
                    written.append(rel)
            else:
                write_text(tmp / "python" / "main.py", IDLE_MAIN)
        write_text(tmp / MARKER, f"iotc {__version__}\n")
        _commit(tmp, out)
    except BaseException:
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    return sorted(written)
