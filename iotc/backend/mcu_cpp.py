"""MCU back end: emits sketch/iotc_gen.h and sketch/sketch.ino (Architecture §11.3).

The header is self-contained standalone C++: configuration macros, program tables (from the same
runtime table the interpreter uses), the fixed core (cpp_core.py), one integer predicate function
per rule / ENSURE, and the Bridge glue whose names come only from bridge.py. DSL names never
become identifiers (ADR-26): they appear only in escaped string tables and in comments that
c_comment_safe() accepts.
"""
from __future__ import annotations

import re

from .. import __version__
from ..escape import c_comment_safe, cpp_str
from ..ir import AvgTest, CodeRange, IRProgram
from ..table import build_table
from . import bridge
from .cpp_core import CORE_DECL, CORE_PASS
from .profiles import Profile, get_profile

OP_NAME = {">": "OP_GT", ">=": "OP_GE", "<": "OP_LT", "<=": "OP_LE", "==": "OP_EQ"}
INPUT_MODES = ("pins", "sim", "scenario")


def _arr(n: int) -> int:
    return n if n > 0 else 1


def _list(values, fmt=str) -> str:
    vals = [fmt(v) for v in values] or ["0"]
    return "{ " + ", ".join(vals) + " }"


def _safe_path(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_./-]", "_", name)


def _test_expr(ir: IRProgram, t) -> str:
    if isinstance(t, CodeRange):
        if t.never:
            return "false"
        if t.var.agg is None:
            c = f"code[{ir.sensor(t.var.sensor).id}]"
            parts = []
            if t.lo is not None:
                parts.append(f"{c} >= {t.lo}")
            if t.hi is not None:
                parts.append(f"{c} <= {t.hi}")
            return " && ".join(parts) if parts else "true"
        w = ir.window_for(t.var).id
        lo = -1 if t.lo is None else t.lo
        hi = -1 if t.hi is None else t.hi
        return f"winRange({w}, {'true' if t.var.agg == 'max' else 'false'}, {lo}, {hi})"
    assert isinstance(t, AvgTest)
    return f"winAvg({ir.window_for(t.var).id}, {OP_NAME[t.op]}, {t.p}LL, {t.q}LL)"


def _predicate(name: str, comment: str, ir: IRProgram, tests, on_mcu: bool) -> str:
    if not on_mcu:
        body, comment = "return false;", comment + " (evaluated on Linux)"
    else:
        exprs = [_test_expr(ir, t) for t in tests] or ["true"]
        body = "return " + " && ".join(f"({e})" for e in exprs) + ";"
    return f"IOTC_UNUSED static bool {name}() {{ {body} }}  // {comment}"


def emit(ir: IRProgram, input_mode: str = "pins", scenario: list[list[int]] | None = None) -> dict[str, str]:
    """Return {"iotc_gen.h": ..., "sketch.ino": ...} for the program's board and target."""
    if input_mode not in INPUT_MODES:
        raise ValueError(input_mode)
    if input_mode == "scenario" and not scenario:
        raise ValueError("--input scenario needs --scenario")
    prof: Profile = get_profile(ir.board)
    table = build_table(ir)
    bridge_on = ir.target == "unoq"
    serial_log = ir.board == "uno"
    matrix_on = prof.has_matrix
    n_sens, n_act, n_rule = len(ir.sensors), len(ir.actuators), len(ir.rules)
    n_never, n_ens, n_win = len(ir.nevers), len(ir.ensures), len(ir.windows)
    n_fs = len(table["fs"])
    out: list[str] = []
    w = out.append

    w(f"// GENERATED by iotc {__version__} from {_safe_path(ir.name)} sha256:{ir.source_sha[:16]} "
      f"(board {ir.board}, target {ir.target}, input {input_mode}) - do not edit")
    w("#pragma once")
    w("#include <Arduino.h>")
    if bridge_on:
        w("#include <Arduino_RouterBridge.h>")
    if matrix_on:
        w("#include <Arduino_LED_Matrix.h>")
    w("")
    w(f"#define IOTC_BRIDGE {int(bridge_on)}")
    w(f"#define IOTC_MATRIX {int(matrix_on)}")
    w(f"#define IOTC_SERIAL_LOG {int(serial_log)}")
    for m in INPUT_MODES:
        w(f"#define IOTC_INPUT_{m.upper()} {int(input_mode == m)}")
    w(f"#define IOTC_HAS_SCENARIO {int(bool(scenario))}")
    w("")
    w("#define IOTC_UNUSED __attribute__((unused))")
    w("namespace iotc {")
    w("typedef " + ("pin_size_t" if ir.board == "unoq" else "uint8_t") + " pin_t;")
    w(f"#define DIGITAL_INPUT_MODE {'INPUT_PULLDOWN' if ir.board == 'unoq' else 'INPUT'}")

    # --- sizes and timing
    deadlines = [r.deadline_ms for r in ir.rules if r.deadline_ms is not None and r.placement == "MCU"]
    w(f"static const uint8_t N_SENS = {n_sens}, N_ACT = {n_act}, N_RULE = {n_rule}, N_NEVER = {n_never};")
    w(f"static const uint8_t N_ENSURE = {n_ens}, N_WIN = {n_win}, N_FS = {n_fs};")
    for name, n in (("SENS", n_sens), ("ACT", n_act), ("RULE", n_rule), ("NEVER", n_never),
                    ("ENSURE", n_ens), ("WIN", n_win), ("FS", n_fs)):
        w(f"static const uint8_t N_{name}_A = {_arr(n)};")
    w(f"static const uint32_t SAMPLE_MS = {ir.sample_ms}, FAILSAFE_TIMEOUT_MS = {ir.failsafe_timeout_ms};")
    w("static const uint32_t SIM_TIMEOUT_MS = 3000;")
    w(f"static const uint32_t DEADLINE_US = {min(deadlines) * 1000 if deadlines else 0};")

    # --- sensors
    w(f"static const pin_t SENS_PIN[N_SENS_A] = {_list([prof.cpp_pin(s.pin) for s in ir.sensors])};")
    w(f"static const uint8_t SENS_DIGITAL[N_SENS_A] = {_list([int(s.kind == 'DIGITAL') for s in ir.sensors])};")
    w(f"static const uint16_t SENS_ADC_MAX[N_SENS_A] = {_list([s.adc_max for s in ir.sensors])};")
    init_codes = list(scenario[0]) if scenario else [s.adc_max // 2 if s.kind == "ANALOG" else 0 for s in ir.sensors]
    w(f"static const uint16_t SENS_INIT[N_SENS_A] = {_list(init_codes)};")

    # --- actuators
    w(f"static const pin_t ACT_PIN[N_ACT_A] = {_list([prof.cpp_pin(a.pin) for a in ir.actuators])};")
    w(f"static const uint8_t ACT_ACTIVE_LOW[N_ACT_A] = {_list([int(a.active_low) for a in ir.actuators])};")
    w(f"static const uint8_t ACT_INIT[N_ACT_A] = {_list([int(a.init == 'ON') for a in ir.actuators])};")
    w(f"static const char* const ACT_NAME[N_ACT_A] = {_list([cpp_str(a.name) for a in ir.actuators])};")

    # --- windows (slots only for MCU-side windows)
    offs, slots = [], 0
    for win in ir.windows:
        offs.append(slots)
        if win.on_mcu:
            slots += win.buckets
    w(f"static const uint8_t WIN_SENSOR[N_WIN_A] = {_list([x.sensor_id for x in ir.windows])};")
    w(f"static const uint32_t WIN_MS[N_WIN_A] = {_list([x.window_ms for x in ir.windows])};")
    w(f"static const uint8_t WIN_B[N_WIN_A] = {_list([x.buckets for x in ir.windows])};")
    w(f"static const uint8_t WIN_MCU[N_WIN_A] = {_list([int(x.on_mcu) for x in ir.windows])};")
    w(f"static const uint16_t WIN_OFF[N_WIN_A] = {_list(offs)};")
    w(f"static const uint16_t N_SLOTS_A = {_arr(slots)};")

    # --- rules
    rules = table["rules"]
    w(f"static const uint8_t RULE_SET[N_RULE_A] = {_list([int(r['action'][0] == 'set') for r in rules])};")
    w(f"static const uint8_t RULE_ACT[N_RULE_A] = {_list([r['action'][1] if r['action'][0] == 'set' else 0 for r in rules])};")
    w(f"static const uint8_t RULE_STATE[N_RULE_A] = {_list([r['action'][2] if r['action'][0] == 'set' else 0 for r in rules])};")
    w(f"static const uint8_t RULE_MCU[N_RULE_A] = {_list([int(r['placement'] == 'MCU') for r in rules])};")
    w(f"static const uint8_t RULE_MASKBIT[N_RULE_A] = {_list([r['mask_bit'] if r['mask_bit'] is not None else 0xFF for r in rules])};")
    w(f"static const uint32_t RULE_HOLD[N_RULE_A] = {_list([r['hold_ms'] or 0 for r in rules])};")
    w(f"static const char* const RULE_NAME[N_RULE_A] = {_list([cpp_str(r['name']) for r in rules])};")
    w(f"static const char* const RULE_TEXT[N_RULE_A] = {_list([cpp_str(r['action'][1] if r['action'][0] == 'notify' else '') for r in rules])};")

    # --- safety
    w(f"static const uint8_t NEV[N_NEVER_A][4] = {_list([_list(n) for n in table['nevers']])};")
    starts, lens, cl_act, cl_state = [], [], [], []
    for e in table["ensures"]:
        starts.append(len(cl_act))
        lens.append(len(e["closure"]))
        cl_act += [a for a, _ in e["closure"]]
        cl_state += [s for _, s in e["closure"]]
    w(f"static const uint8_t ENS_CL_START[N_ENSURE_A] = {_list(starts)};")
    w(f"static const uint8_t ENS_CL_LEN[N_ENSURE_A] = {_list(lens)};")
    w(f"static const uint8_t CL_ACT[{_arr(len(cl_act))}] = {_list(cl_act)};")
    w(f"static const uint8_t CL_STATE[{_arr(len(cl_state))}] = {_list(cl_state)};")
    w(f"static const uint8_t FS_ACT[N_FS_A] = {_list([a for a, _ in table['fs']])};")
    w(f"static const uint8_t FS_STATE[N_FS_A] = {_list([s for _, s in table['fs']])};")

    # --- LED matrix layout (§11.8)
    mx = table["matrix"]
    ticks, tstart, tlen = [], [], []
    for b in mx["bars"]:
        tstart.append(len(ticks))
        tlen.append(len(b["ticks"]))
        ticks += b["ticks"]
    w(f"static const uint8_t N_BARS = {len(mx['bars'])}, MX_RULES = {mx['rules']}, MX_ACTS = {mx['acts']};")
    w(f"static const uint16_t BAR_ZLO[{_arr(len(mx['bars']))}] = {_list([b['zlo'] for b in mx['bars']])};")
    w(f"static const uint16_t BAR_ZHI[{_arr(len(mx['bars']))}] = {_list([b['zhi'] for b in mx['bars']])};")
    w(f"static const uint8_t BAR_TICK_START[{_arr(len(mx['bars']))}] = {_list(tstart)};")
    w(f"static const uint8_t BAR_TICK_LEN[{_arr(len(mx['bars']))}] = {_list(tlen)};")
    w(f"static const uint16_t TICKS[{_arr(len(ticks))}] = {_list(ticks)};")

    # --- scenario table (§9.2)
    rows = scenario or [[0] * n_sens]
    w(f"static const uint16_t N_SCEN = {len(rows)};")
    w(f"static const uint16_t SCEN[{len(rows)}][N_SENS_A] = {_list([_list(r) for r in rows])};")

    # --- Bridge names (only from bridge.py)
    if bridge_on:
        for m in bridge.MESSAGES:
            w(f"static const char BR_{m.name.upper()}[] = {cpp_str(m.name)};")

    out.append(CORE_DECL)

    # --- generated predicates
    w("// ===== generated predicates: integer code tests (ADR-17) =====")
    names = []
    for r in ir.rules:
        fn = f"pred_r{r.id}"
        names.append(fn)
        w(_predicate(fn, f"rule {c_comment_safe(r.name)}", ir, r.tests, r.placement == "MCU"))
    if not names:
        w("IOTC_UNUSED static bool pred_none() { return false; }")
        names = ["pred_none"]
    w(f"static bool (*const RULE_PRED[N_RULE_A])() = {_list(names)};")
    enames = []
    for e in ir.ensures:
        fn = f"pred_e{e.id}"
        enames.append(fn)
        w(_predicate(fn, f"ENSURE {e.id + 1}", ir, e.tests, True))
    if not enames:
        w("IOTC_UNUSED static bool pred_no_ensure() { return false; }")
        enames = ["pred_no_ensure"]
    w(f"static bool (*const ENS_PRED[N_ENSURE_A])() = {_list(enames)};")
    if bridge_on:
        args = "".join(f", code[{i}]" for i in range(n_sens))
        w(f"IOTC_UNUSED static void streamSample(uint32_t t) {{ Bridge.notify(BR_SAMPLE, t{args}); }}")

    out.append(CORE_PASS)
    w("}  // namespace iotc")
    header = "\n".join(out).replace("\r", "") + "\n"
    ino = ("// GENERATED by iotc - all logic lives in iotc_gen.h\n"
           "#include \"iotc_gen.h\"\n\n"
           "void setup() { iotc::setup(); }\n"
           "void loop() { iotc::loop(); }\n")
    return {"iotc_gen.h": header, "sketch.ino": ino}
